PI = {s: rd(s, "final_per_instance.csv") for s in S}
PS = {s: rd(s, "paired_stats.csv") for s in S}
DG = {s: rd(s, "diagnostics.csv") for s in S}
FS = {s: rd(s, "final_summary.csv") for s in S}
