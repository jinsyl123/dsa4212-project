N = ["# Values quoted in the report text. Generated by code/pipeline/make_report_assets.py; do not edit by hand, rerun the script.",
     "# Each block names the committed file(s) under code/results/ its values are computed from."]
def note(k, v): N.append(f"{k}: {v}")
def source(s): N.append(f"\n# from {s}")                # starts a block of numbers.txt
def header(*lines): return "".join(f"% {l}\n" for l in lines)   # LaTeX comments: not shown in the PDF

def mean_excess(s, kind):
    d = PI[s]; d = d[(d.kind == kind) & d.set.isin(map(T, SETS))]
    g = d.groupby(["seed", "set"]).excess_l2.mean().unstack() * 100
    return g
def btuw(v): return "/".join(str((v == k).sum()) for k in ("better", "tie", "unclear", "worse"))
def bw(s, kind, ref, seeds=None):
    d = PS[s]; d = d[(d.kind == kind) & (d.reference == ref)]
    if seeds is not None: d = d[d.seed.isin(seeds)]
    return [btuw(d[d.set == T(x)].verdict) for x in SETS]
BF = PI["Baseline"]; BF = BF[BF.label == "best_fit"].groupby("set").excess_l2.mean() * 100
def fmt(v): return "{:.2f}".format(v) if v < 100 else "{:.0f}".format(v)
def row(label, cells): return label + " & " + " & ".join(cells) + r" \\"
def means(s, kind):                              # same source and rounding as summary_tables.md
    f = FS[s]; g = f[f.kind == kind].set_index("set").mean_excess_l2 * 100; return [fmt(g[T(x)]) for x in SETS]
def table(path, rows, settings):
    spec = "@{}l" + "r" * len(SETS) + "@{}"
    src = header("Generated by code/pipeline/make_report_assets.py; do not edit by hand, rerun the script.",
                 f"Sources, under code/results/: excess means from <setting>/final_summary.csv for {settings} (Best Fit's row from",
                 "the baseline's final_per_instance.csv); B/T/U/W verdict counts from <setting>/paired_stats.csv.")
    open(f"{OUT}/tables/{path}.tex", "w").write(src + "\\scriptsize\\setlength{\\tabcolsep}{2.5pt}\\begin{tabular}{" + spec + "}\n\\toprule\n" + row("", HEAD) + "\n\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
bfrow = row("Best Fit, excess \\%", [fmt(BF[T(x)]) for x in SETS])
def block(s, name, tuned_label=None):
    r = [row(f"{name}, excess \\%", means(s, "evolved")), row("\\quad vs Best Fit (B/T/U/W)", bw(s, "evolved", "best_fit")), row("\\quad vs tuned (B/T/U/W)", bw(s, "evolved", "tuned_bf"))]
    if tuned_label: r.append(row(f"{tuned_label}, excess \\%", means(s, "tuned")))
    return r
table("baseline", [bfrow, row("Tuned Best Fit, excess \\%", means("Baseline", "tuned")), row("\\quad vs Best Fit (B/T/U/W)", bw("Baseline", "tuned", "best_fit"))] + block("Baseline", "Baseline"), "the baseline")
table("ablation1", block("A1a", "A1a", "Tuned, AnyFit") + block("A1b", "A1b") + block("Control", "Control"), "A1a, A1b and the control")
table("ablation2", block("A2a", "A2a", "Tuned, mixed shapes") + block("A2b", "A2b", "Tuned, mixed capacities"), "A2a and A2b")

