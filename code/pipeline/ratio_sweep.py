"""Report §5.5, check 3: the item-to-bin ratio. A1b's rules on new instances at smaller item-to-bin ratios.

Usage, from code/:
    python pipeline/ratio_sweep.py
A1b seed 0 scores a used bin -(1 + g/C)^3 and an empty bin -2.5, so an empty bin wins when a used bin would be left
with more than ~36% of its capacity; a bin holding one item of relative size rho is left with 1 - 2*rho after a
second, which predicts failure below rho ~ 0.32 (prediction recorded before this sweep was run; report §5.5).
New sets, generated by obpevo.instances with the v0 base seed (2026) and the set names below, so they are
deterministic: capacity 100, Weibull(3) items with the scale chosen so the mean item is rho of a bin (rho = 0.36 ...
0.13; training is ~0.40), 5 instances x 2,000 items each; plus capacity 1,000 at the training ratio (scale 450,
training x 10). Writes results/abl_informed_rules/ratio_sweep.csv: excess over L2 per seed and set, Best Fit's, the
difference in pp (negative = better) and the actual mean item / capacity. Pre-allocated (funsearch) packing, as in
the search. No LLM calls. Exploratory: designed after A1 was scored (code/docs/log.md, 12 Nov).
"""
from __future__ import annotations

from math import gamma

import numpy as np
import pandas as pd

from obpevo import config as C, instances
from masked_choice import CONFIG, SEEDS, best_fit, excess_l2, load_priority

BASE_SEED = 2026                                          # configs/instances/v0.yaml
RHOS = [0.36, 0.31, 0.27, 0.23, 0.18, 0.13]
WEIBULL3_MEAN = gamma(1 + 1 / 3)                           # mean of Weibull(shape 3) per unit scale, ~0.893
N_INST, N_ITEMS = 5, 2000


def sweep_sets() -> dict[str, tuple[float, list[dict]]]:
    specs = {f"sweep_rho{r:.2f}": (r, dict(n_instances=N_INST, n_items=N_ITEMS, capacity=100, dist="weibull", shape=3,
                                            scale=round(100 * r / WEIBULL3_MEAN, 2))) for r in RHOS}
    specs["sweep_cap1000"] = (0.40, dict(n_instances=N_INST, n_items=N_ITEMS, capacity=1000, dist="weibull", shape=3,
                                         scale=450))
    return {name: (r, instances.generate_set(name, spec, base_seed=BASE_SEED)) for name, (r, spec) in specs.items()}


def main() -> pd.DataFrame:
    cfg = C.load(CONFIG)
    res = C.results_dir(cfg)
    sets = sweep_sets()
    bf = {s: excess_l2(best_fit, insts, "funsearch") for s, (_, insts) in sets.items()}
    rows = []
    for k in SEEDS:
        prio = load_priority(res / "eoh" / f"seed{k}" / "best_program.py")
        for s, (r, insts) in sets.items():
            x = excess_l2(prio, insts, "funsearch")
            rho = float(np.mean([i["items"].mean() / i["capacity"] for i in insts]))
            rows.append(dict(seed=k, set=s, capacity=insts[0]["capacity"], rho_target=r, rho_actual=round(rho, 4),
                             excess_l2_pct=round(100 * x, 4), best_fit_pct=round(100 * bf[s], 4),
                             delta_pp=round(100 * (x - bf[s]), 4)))
            print(f"seed {k} {s:15} rho {rho:.3f}  {100 * x:9.3f}%  vs Best Fit {100 * (x - bf[s]):+9.3f} pp")
    out = pd.DataFrame(rows)
    out.to_csv(res / "ratio_sweep.csv", index=False)
    print(f"-> {res / 'ratio_sweep.csv'}")
    return out


if __name__ == "__main__":
    main()
